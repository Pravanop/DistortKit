"""Crystallographic tables.

* Space groups (``tables/space_groups.json``) and Wyckoff positions (``tables/wyckoff.json``) are open data generated
  by ``tools/build_tables.py`` (operations from spglib's database, special positions computed from them, letters from
  spglib); verified against the ISOTROPY tables by ``tools/verify_tables.py``.
* Irrep labels (X5+, R4+, ...) come from the ISOTROPY data tables ``data_isotropy.txt`` and ``data_irreps.txt``
  (Stokes, Hatch, Campbell, BYU; see NOTICE), bundled in ``tables/``.  They are plain text: a line holding an array
  name, followed by whitespace-separated integers or double-quoted strings.  To use another copy set the
  ``ISODATA`` environment variable or call ``set_data_dir()``.  Without them everything works except the label names.
"""
from __future__ import annotations

import json
import os
import re
from fractions import Fraction
from functools import lru_cache

import numpy as np

_DIR = None


def set_data_dir(path):
    global _DIR
    _DIR = os.path.abspath(path)
    get_tables.cache_clear()


BUNDLED = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tables")


def data_dir():
    """Directory with the ISOTROPY label tables: set_data_dir(), $ISODATA, then the copy bundled in the package."""
    for d in (_DIR, os.environ.get("ISODATA"), BUNDLED):
        if d and os.path.isfile(os.path.join(d, "data_isotropy.txt")) and os.path.isfile(os.path.join(d, "data_irreps.txt")):
            return d
    raise FileNotFoundError(
        "ISOTROPY label tables not found. Set the ISODATA environment variable to the directory containing "
        "data_isotropy.txt and data_irreps.txt (irrep labels need them; everything else works without)")


def labels_available():
    try:
        data_dir()
        return True
    except FileNotFoundError:
        return False


@lru_cache(maxsize=None)
def get_tables(name):
    """Parse ``data_<name>.txt`` into {array name: raw text}."""
    path = os.path.join(data_dir(), f"data_{name}.txt")
    out, cur = {}, None
    with open(path) as fh:
        for line in fh:
            s = line.rstrip("\n")
            if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*\s*", s):
                cur = s.strip()
                out[cur] = []
            elif cur:
                out[cur].append(s)
    return {k: " ".join(v) for k, v in out.items()}


def ints(tables, name):
    return np.array(tables[name].split(), dtype=np.int64)


def strings(tables, name):
    return re.findall(r'"([^"]*)"', tables[name])


# ---------------------------------------------------------------- space groups
class SpaceGroupData:
    """One of the 230 space groups in the International Tables default setting (origin choice 2 where there are two)."""

    def __init__(self, number, symbol, full, schoenflies, point_group, ops, centering):
        self.number = number
        self.symbol = symbol          # short Hermann-Mauguin symbol, e.g. "Pnma"
        self.full = full
        self.schoenflies = schoenflies
        self.point_group = point_group   # Hermann-Mauguin point group, e.g. "mmm"
        self.ops = ops                # list of (R int 3x3, t tuple of Fractions) in the conventional cell
        self.centering = centering    # list of Fraction triples (nonzero centering translations)

    def __repr__(self):
        return f"<SpaceGroup {self.number} {self.symbol} ({len(self.ops)} ops in the conventional cell)>"


@lru_cache(maxsize=None)
def space_groups():
    """The 230 space groups, read from ``tables/space_groups.json`` (generated by ``tools/build_tables.py``)."""
    with open(os.path.join(BUNDLED, "space_groups.json")) as fh:
        doc = json.load(fh)["groups"]
    out = {}
    for g in range(1, 231):
        rec = doc[str(g)]
        ops = [(np.array(R, dtype=int).reshape(3, 3), tuple(Fraction(v) for v in t)) for R, t in rec["ops"]]
        cent = [t for R, t in ops if np.array_equal(R, np.eye(3, dtype=int)) and any(t)]
        out[g] = SpaceGroupData(g, rec["symbol"], rec["full"], rec["schoenflies"], rec["point_group"], ops, cent)
    return out
